export function translate(key, params = {}) {
  if (!Object.hasOwn(STRINGS, key)) throw new Error(`Missing string: ${key}`);
  return STRINGS[key].replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}
